import { test, expect } from '@playwright/test'

test('native public link buttons keep Forest contrast, including the portalled mobile editor', async ({page,baseURL}) => {
  await page.route('**/*', r=>{const u=new URL(r.request().url());return u.origin===new URL(baseURL!).origin&&!u.pathname.startsWith('/api/')?r.continue():r.abort()})
  await page.setViewportSize({width:320,height:1000});await page.goto('/app')
  await expect(page.getByRole('button',{name:'Ask a question',exact:true})).toHaveCSS('color','rgb(23, 61, 50)')
  await page.getByRole('button',{name:'Edit draft details',exact:true}).click()
  const editor=page.getByRole('dialog',{name:'Task panel',exact:true})
  await expect(editor.getByRole('button',{name:'Back to summary',exact:true})).toHaveCSS('color','rgb(23, 61, 50)')
})

test('05 operational notes are small-body 12/20 and success is delivery-specific, then neutral after a block', async ({ page }) => {
  await page.setViewportSize({width:1520,height:1379}); await page.goto('/demo')
  await page.getByText('Demo controls',{exact:true}).click()
  for(const name of ['Open external proposal','Authorize mandate','Confirm funding','S03 · Deliver company records']) await page.getByRole('button',{name,exact:true}).click()
  await expect(page.locator('.conversation-spending-actions .spending-actions p')).toHaveCSS('font-size','12px')
  await expect(page.locator('.conversation-spending-actions .spending-actions p')).toHaveCSS('line-height','20px')
  await expect(page.locator('.composer-limit')).toHaveCSS('line-height','20px')
  await expect(page.locator('.panel-amendment-note')).toHaveText('Changing permissions needs an explicit amendment and re-authorization.')
  await expect(page.locator('.panel-amendment-note')).toHaveCSS('font-size','12px')
  const delivered = page.locator('.panel-results .order-result').first().locator('p').first()
  await expect(delivered).toHaveCSS('color','rgb(47, 107, 79)')
  await expect(page.locator('.panel-status')).toHaveCSS('color','rgb(21, 37, 31)')
  await page.getByRole('button',{name:'S04 · Excluded recipient request',exact:true}).click()
  await expect(delivered).toHaveCSS('color','rgb(68, 87, 74)')
  // Approved blocked response is inline, with the existing warning token, not a filled card.
  await expect(page.locator('.agent-work[data-tone="warning"]')).toHaveCSS('background-color','rgba(0, 0, 0, 0)')
  await expect(page.locator('.agent-work[data-tone="warning"] .agent-work-current')).toHaveCSS('color','rgb(133, 90, 19)')
  await expect(page.locator('.mandate-change-requirement')).toHaveCSS('font-size','14px')
  await expect(page.locator('.mandate-change-requirement')).toHaveCSS('line-height','20px')
})

