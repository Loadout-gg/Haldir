import { fileURLToPath } from 'node:url'
import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { writeFileSync } from 'node:fs'
const evidence = process.env.HALDIR_EVIDENCE_DIR || fileURLToPath(new URL('../../../test-results/brand', import.meta.url))
const panel = (page: Page) => page.getByRole('complementary', {name:'Working bar',exact:true})
const conversation = (page: Page) => page.getByRole('region', { name:'Conversation', exact:true })
async function control(page: Page, name: string) {
  const d = page.locator('.demo-controls')
  if (await d.getAttribute('open') === null) await d.locator('summary').click()
  await d.getByRole('button', { name, exact:true }).click()
  await d.evaluate(el => (el as HTMLDetailsElement).open = false)
  await page.evaluate(() => window.scrollTo(0,0))
}

test('actual branded states remain accessible across funding, payments, blocks, stop, return and retained results', async ({ page }) => {
  test.setTimeout(120000)
  await page.setViewportSize({ width:1440,height:1000 })
  const errors: string[] = [], remote: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  await page.route('**/*', route => {
    if (new URL(route.request().url()).origin === new URL(test.info().project.use.baseURL!).origin) return route.continue()
    remote.push(route.request().url()); return route.abort()
  })
  await page.goto('/demo')
  await page.evaluate(() => document.fonts.ready)
  const reports: unknown[] = []
  async function audit(state: string, screenshot?: string) {
    await page.evaluate(() => window.scrollTo(0,0))
    const axe = await new AxeBuilder({ page }).analyze()
    // Preserve real accessibility RED while auditing the remaining state matrix.
    expect.soft(axe.violations, state).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), state).toBe(true)
    const pairs = await page.evaluate(() => {
      const sels = ['.current-note','.blocked-request','.funding-error','.funding-pending','[data-slot="badge"]','[data-variant="brand-primary"]','[data-variant="brand-dark"]','.composer','textarea','[data-slot="input"]']
      return sels.flatMap(selector => [...document.querySelectorAll(selector)].filter(el => el.getClientRects().length).map(el => {
        const s = getComputedStyle(el); return { selector, label:el.textContent?.slice(0,100), color:s.color, bg:s.backgroundColor, gradient:s.backgroundImage, border:s.borderTopColor, outline:s.outlineColor, opacity:s.opacity, disabled:(el as HTMLButtonElement).disabled || false }
      }))
    })
    reports.push({ state, violations:axe.violations, incomplete:axe.incomplete.map(x => ({ id:x.id, nodes:x.nodes.map(n => ({ target:n.target, html:n.html, summary:n.failureSummary })) })), pairs })
    writeFileSync(`${evidence}/state-a11y.json`,JSON.stringify({ errors,remote,reports },null,2))
    if (screenshot) await page.screenshot({ path:`${evidence}/${screenshot}.png`, animations:'disabled' })
  }
  await audit('entry','01-initial-desktop')
  await page.getByRole('textbox', { name: 'Your message' }).fill('budget 30')
  await page.getByRole('textbox', { name: 'Your message' }).press('Enter')
  await audit('draft')
  await conversation(page).getByRole('button', { name:'Edit details',exact:true }).click()
  const editor = page.getByRole('region', { name:'Edit draft details',exact:true })
  const input = editor.getByLabel('Purchase budget (TEST)')
  await input.focus()
  expect(await input.evaluate(el => getComputedStyle(el).outlineStyle)).toBe('solid')
  await audit('editor-focused-input')
  await editor.getByLabel('Permission expiry (UTC)').fill('2026-11-12T18:00')
  await editor.getByRole('button',{name:'Save draft',exact:true}).click()
  await conversation(page).getByRole('button',{name:'Review spending limits',exact:true}).click()
  await conversation(page).locator('.conversation-stream').evaluate(el => el.scrollTop = 0)
  await audit('review','02-review-desktop')
  await page.getByRole('button', { name:'Authorize mandate' }).click()
  await audit('funding-pending')
  await control(page,'Fail funding')
  await audit('funding-failed')
  await conversation(page).getByRole('button', { name:'Retry funding request' }).click()
  await control(page,'Confirm funding')
  await audit('active')
  await control(page,'Start company records payment')
  await audit('payment-pending')
  await control(page,'Make company records payment uncertain')
  await audit('payment-uncertain')
  await panel(page).getByRole('button', { name:'Check company records payment' }).click()
  await control(page,'Confirm company records payment')
  await audit('paid-delivery-missing')
  await panel(page).getByRole('button', { name:/^(?:Open company records receipt|Open receipt — company records)$/ }).click()
  await audit('receipt-awaiting-data')
  await page.keyboard.press('Escape')
  await panel(page).getByRole('button', { name:'Recover company records delivery' }).click()
  await audit('delivery-retrieval-requested')
  await control(page,'Deliver company records response')
  await conversation(page).locator('.conversation-stream').evaluate(el => el.scrollTop = 0)
  await audit('working-first-result','03-working-desktop')
  await control(page,'S04 · Excluded recipient request')
  await conversation(page).getByRole('heading', { name:'Payment blocked · Recipient not allowed' }).scrollIntoViewIfNeeded()
  await audit('excluded-recipient','04-blocked-desktop')
  await conversation(page).getByRole('button', { name:'Continue without this purchase' }).click()
  await control(page,'S05 · Two requests together')
  await audit('insufficient-budget-concurrent-reservation')
  await control(page,'S06 · Deliver background research')
  await audit('both-delivered')
  await panel(page).getByRole('button', { name:'Open partial brief' }).click()
  await audit('partial-brief')
  await page.getByRole('dialog', { name:'Northwind Print · Partial brief' }).getByRole('button', { name:/^(?:Open company records receipt|Open receipt — company records)$/ }).click()
  await audit('nested-receipt')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await conversation(page).getByRole('button', { name:'Stop new spending' }).click()
  await audit('stop-requested')
  await control(page,'Confirm stop')
  await audit('stop-confirmed')
  await conversation(page).getByRole('button', { name:'Check prior payments' }).click()
  await conversation(page).getByRole('button', { name:'Request return of 7 TEST' }).click()
  await audit('return-pending')
  await control(page,'Make return uncertain')
  await audit('return-uncertain')
  await control(page,'Confirm return')
  await conversation(page).getByRole('button', { name:'Continue without this purchase' }).click()
  await conversation(page).locator('.conversation-stream').evaluate(el => el.scrollTop = 0)
  await panel(page).evaluate(el => el.scrollTop = 0)
  await audit('closed','05-completion-desktop')
  await panel(page).getByRole('button', { name:'Open partial brief' }).scrollIntoViewIfNeeded()
  await audit('closed-retained-results','05b-completion-retained-results')
  await conversation(page).locator('.conversation-stream').evaluate(el => el.scrollTop = 0)
  await panel(page).getByRole('button',{name:'Hide panel',exact:true}).click()
  await page.setViewportSize({ width:390,height:844 })
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await audit('closed-mobile','06-completion-mobile')
  const trigger = page.getByRole('button', { name:'Task panel', exact:true })
  await trigger.click()
  const sheet = panel(page)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await sheet.getByRole('heading', { name:'Spending', exact:true }).scrollIntoViewIfNeeded()
  await audit('closed-mobile-workingbar','07-mobile-workingbar')
  await sheet.getByRole('button', { name:/^(?:Open company records receipt|Open receipt — company records)$/ }).click()
  await audit('closed-mobile-nested-receipt')
  await page.keyboard.press('Escape')
  await expect(sheet.getByRole('button', { name:/^(?:Open company records receipt|Open receipt — company records)$/ })).toBeFocused()
  await sheet.getByRole('button',{name:'Hide panel',exact:true}).click()
  await expect(page.getByRole('button',{name:'Show task panel',exact:true})).toBeFocused()
  // Exercise an actual failed-payment plain status independently of earlier uncertain/paid path.
  await page.goto('/demo')
  await page.getByRole('textbox', { name: 'Your message' }).fill('budget 30; expiry 2026-11-12T18:00')
  await page.getByRole('textbox', { name: 'Your message' }).press('Enter')
  await expect(page.getByRole('heading', { name:'Proposed spending mandate' })).toBeVisible()
  await page.getByRole('button', { name:'Authorize mandate' }).click()
  await control(page,'Confirm funding')
  await control(page,'Start company records payment')
  await control(page,'Confirm failed company records payment')
  await audit('failed-payment-mobile')
  expect(errors).toEqual([])
  expect(remote).toEqual([])
  writeFileSync(`${evidence}/state-a11y.json`,JSON.stringify({ errors,remote,reports },null,2))
})
