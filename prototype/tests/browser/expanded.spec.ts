import { fileURLToPath } from 'node:url'
import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
const panel = (page: Page) => page.getByRole('complementary', { name: 'Working bar', exact: true })
const evidence = process.env.HALDIR_EVIDENCE_DIR ? `${process.env.HALDIR_EVIDENCE_DIR}/scenario-regressions` : fileURLToPath(new URL('../../../test-results/scenario-regressions', import.meta.url))

test('mobile S01–S08 full path preserves results through a block, closes spending only after return confirmation', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/demo')
  const w = page.getByRole('region', { name: 'Conversation', exact: true })
  async function event(name: string) {
    const d = page.locator('.demo-controls')
    if (await d.getAttribute('open') === null) await d.locator('summary').click()
    await d.getByRole('button', { name, exact: true }).click()
  }
  async function image(name: string) {
    await page.locator('.demo-controls').evaluate(el => (el as HTMLDetailsElement).open = false)
    await page.evaluate(() => window.scrollTo(0,0))
    await page.screenshot({ path: `${evidence}/${name}.png` })
  }
  await page.getByRole('textbox', { name: 'Your message' }).fill('budget 30')
  await page.getByRole('textbox', { name: 'Your message' }).press('Enter')
  await page.getByRole('textbox', { name: 'Your message' }).fill('budget 30')
  await page.getByRole('textbox', { name: 'Your message' }).press('Enter')
  await expect(w.getByRole('log', { name: 'Conversation history' })).toContainText('What expiry should I use? Please confirm the missing information; no values have been assumed.')
  await expect(page.getByRole('button', { name: 'Review spending limits', exact: true })).toBeDisabled()
  await page.getByRole('textbox', { name: 'Your message' }).fill('expiry 2026-11-12T18:00')
  await page.getByRole('textbox', { name: 'Your message' }).press('Enter')
  await expect(w.getByRole('status')).toContainText('Here is the proposed spending mandate. Review the recipients, limit and expiry. Nothing is authorized yet.')
  await expect(page.getByRole('region', { name: 'Spending review', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Authorize mandate' }).scrollIntoViewIfNeeded()
  await image('mobile-review-actions')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.getByRole('button', { name: 'Authorize mandate' }).click()
  await event('Confirm funding')
  await event('S03 · Deliver company records')
  await w.getByRole('button', { name: /^(?:Open company records evidence|Open evidence — company records)$/ }).scrollIntoViewIfNeeded()
  await image('mobile-delivered-result')
  await event('S04 · Excluded recipient request')
  await w.getByRole('heading', { name: 'Payment blocked · Recipient not allowed' }).scrollIntoViewIfNeeded()
  await image('mobile-blocked')
  await w.getByRole('button', { name: 'View details', exact: true }).click()
  await expect(panel(page)).toContainText('DEMO-EXCLUDED-03')
  await panel(page).getByRole('button', { name: 'Continue without this purchase' }).click()
  await event('S05 · Two requests together')
  await expect(panel(page).getByTestId('ledger')).toHaveText('Spent8 TESTReserved15 TESTAvailable7 TESTRecovered0 TEST')
  await event('S06 · Deliver background research')
  await panel(page).getByRole('button', { name: 'Open partial brief' }).click()
  await page.getByRole('dialog', { name: 'Northwind Print · Partial brief' }).getByRole('button', { name: /^(?:Open company records evidence|Open evidence — company records)$/ }).click()
  await expect(page.getByRole('dialog', { name: 'Company records evidence' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await w.getByRole('button', { name: 'Stop new spending' }).click()
  await expect(panel(page).locator('.panel-status').filter({ hasText: /^Stop requested$/ })).toBeVisible()
  await event('Confirm stop')
  await w.getByRole('button', { name: 'Check prior payments' }).click()
  await w.getByRole('button', { name: 'Request return of 7 TEST' }).click()
  await expect(panel(page).locator('.panel-status').filter({ hasText: /^Return pending$/ })).toBeVisible()
  await event('Confirm return')
  await expect(panel(page).getByTestId('ledger')).toHaveText('Spent23 TESTReserved0 TESTAvailable0 TESTRecovered7 TEST')
  await w.locator('.conversation-stream').evaluate(el => el.scrollTop = 0)
  await image('mobile-completion')
  await panel(page).getByRole('button', { name: /^(?:Open background research receipt|Open receipt — background research)$/ }).click()
  await expect(page.getByRole('dialog', { name: 'Background research receipt' })).toContainText('No real transaction')
  await page.keyboard.press('Escape')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('verified payment failure releases reservation once, with no delivered evidence or duplicate funding', async ({ page }) => {
  await page.goto('/demo')
  const w = page.getByRole('region', { name: 'Conversation', exact: true })
  await page.getByRole('textbox', { name: 'Your message' }).fill('budget 30; expiry 2026-11-12T18:00')
  await page.getByRole('textbox', { name: 'Your message' }).press('Enter')
  await expect(page.getByRole('region', { name: 'Spending review', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Authorize mandate' }).click()
  await page.locator('.demo-controls summary').click()
  await page.getByRole('button', { name: 'Confirm funding', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Confirm funding', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Start company records payment', exact: true }).click()
  await expect(panel(page).getByText('Payment pending · Funds reserved · 8 TEST', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Confirm failed company records payment', exact: true }).click()
  await expect(panel(page).getByTestId('ledger')).toHaveText('Spent0 TESTReserved0 TESTAvailable30 TESTRecovered0 TEST')
  await expect(w.getByRole('button', { name: /^(?:Open company records evidence|Open evidence — company records)$/ })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Confirm failed company records payment', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Start company records payment', exact: true })).toBeDisabled()
})

test('removing a recipient from draft prevents its scripted purchase; all spending terms stay explicit', async ({ page }) => {
  await page.goto('/demo')
  const w = page.getByRole('region', { name: 'Conversation', exact: true })
  await page.getByRole('textbox', { name: 'Your message' }).fill('budget 30; expiry 2026-11-12T18:00')
  await page.getByRole('textbox', { name: 'Your message' }).press('Enter')
  await page.getByRole('region', { name: 'Conversation', exact: true }).getByRole('button', { name: 'Edit details', exact: true }).click()
  const editor = page.getByRole('region', { name: 'Edit draft details' })
  await editor.getByLabel('Company records source', { exact: true }).uncheck()
  await editor.getByRole('button', { name: 'Save draft' }).click()
  await page.getByRole('button', { name: 'Review spending limits', exact: true }).click()
  const review = page.getByRole('region', { name: 'Spending review' })
  await expect(review).toContainText('Background research source')
  await expect(review).not.toContainText('Company records source and')
  await expect(review).toContainText('No live network or asset selected')
  await page.getByRole('button', { name: 'Authorize mandate' }).click()
  await page.locator('.demo-controls summary').click()
  await page.getByRole('button', { name: 'Confirm funding', exact: true }).click()
  await page.getByRole('button', { name: 'S03 · Deliver company records', exact: true }).click()
  await expect(w.getByRole('heading', { name: 'Payment blocked · Recipient not allowed' })).toBeVisible()
  await expect(panel(page).getByTestId('ledger')).toHaveText('Spent0 TESTReserved0 TESTAvailable30 TESTRecovered0 TEST')
  await expect(panel(page).getByRole('button', { name: /^(?:Open company records receipt|Open receipt — company records)$/ })).toHaveCount(0)
})
