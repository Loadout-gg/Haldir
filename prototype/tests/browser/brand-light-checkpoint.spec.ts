test('Brand Light B maps approved roles onto the actual app, not the landing', async ({ page }) => {
  await page.goto('/demo')
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(253, 253, 251)')
  await expect(page.locator('.conversation')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(page.locator('.working-bar')).toHaveCSS('background-color', 'rgb(249, 251, 248)')
  await expect(page.locator('.reference-card')).toHaveCSS('background-color', 'rgb(245, 248, 243)')
  await expect(page.locator('.user-intention')).toHaveCSS('background-color', 'rgb(23, 61, 50)')
  await expect(page.locator('.user-intention')).toHaveCSS('color', 'rgb(244, 243, 233)')
  await expect(page.locator('.composer')).toHaveCSS('border-top-color', 'rgb(92, 117, 100)')
  await page.getByLabel('Your message').fill('budget 30; expiry 2026-11-12T18:00')
  await expect(page.getByRole('button', { name: 'Send message', exact: true })).toHaveCSS('background-color','rgb(213, 231, 163)')
  await page.getByLabel('Your message').press('Enter')
  await expect(page.getByRole('button', {name:'Authorize mandate',exact:true})).toHaveCSS('background-color','rgb(213, 231, 163)')
  await expect(page.getByRole('button', {name:'Authorize mandate',exact:true})).toHaveCSS('color','rgb(23, 61, 50)')
  await expect(page.locator('.mandate-card')).toHaveCSS('background-color','rgb(251, 252, 250)')
  await page.goto('/')
  await expect(page.locator('body')).toHaveCSS('background-color','rgb(248, 249, 248)')
})
