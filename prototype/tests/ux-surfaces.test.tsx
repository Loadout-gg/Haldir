import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { expect, test } from 'vitest'
import App from '../src/demo/simulation-app'

async function review() { const user=userEvent.setup(); render(<App/>); await user.click(screen.getByText('Demo controls',{exact:true})); await user.click(screen.getByRole('button',{name:'Open external proposal'})); return user }
async function active(){const user=await review();await user.click(screen.getByRole('button',{name:'Authorize mandate'}));await user.click(screen.getByRole('button',{name:'Confirm funding'}));return user}
test('conversation and delivered results omit Assistant speaker labels while retaining You and simulation disclosure',async()=>{
 const user=userEvent.setup();render(<App/>)
 const conversation=screen.getByRole('region',{name:'Conversation'})
 const history=within(conversation).getByRole('log')
 expect(history).not.toHaveTextContent(/Assistant/i)
 await user.type(screen.getByLabelText('Your message'),'budget 30')
 await user.click(screen.getByRole('button',{name:'Send message'}))
 expect(history).toHaveTextContent('You')
 expect(history).not.toHaveTextContent(/Assistant/i)
 expect(history.querySelectorAll('.assistant-message .message-author')).toHaveLength(0)
 expect(history.querySelector('.user-intention .message-author')).toHaveTextContent('You')
 expect(screen.getByRole('region',{name:'Preview notice'})).toHaveTextContent('Scripted simulation')
 await user.click(screen.getByText('Demo controls',{exact:true}))
 await user.click(screen.getByRole('button',{name:'Reset demo'}))
 await user.click(screen.getByRole('button',{name:'Open external proposal'}))
 await user.click(screen.getByRole('button',{name:'Authorize mandate'}))
 await user.click(screen.getByRole('button',{name:'Confirm funding'}))
 await user.click(screen.getByRole('button',{name:'S03 · Deliver company records'}))
 expect(conversation.querySelector('.result-notification > .agent-name')).toHaveTextContent('Haldir')
 expect(conversation.querySelector('.result-notification > p')).toHaveTextContent(/^Company records received\./)
 expect(conversation).not.toHaveTextContent(/Assistant/i)
 expect(screen.getByRole('complementary',{name:'Working bar'})).not.toHaveTextContent(/Assistant/i)
})
