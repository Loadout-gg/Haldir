import { fileURLToPath } from 'node:url'
import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
const panel = (page: Page) => page.getByRole('complementary', { name: 'Working bar', exact: true })
const evidence = process.env.HALDIR_EVIDENCE_DIR || fileURLToPath(new URL('../../../test-results/brand', import.meta.url))

for (const width of [1440,768,390,320]) {
  test(`branded main states and nested readers fit ${width}px`, async ({ page }) => {
    test.setTimeout(60000)
    await page.setViewportSize({ width,height:width < 760 ? 844 : 1000 })
    await page.route('**/*', r => r.request().url().startsWith(`${new URL(test.info().project.use.baseURL!).origin}/`) ? r.continue() : r.abort())
    await page.goto('/demo')
    await page.evaluate(() => document.fonts.ready)
    const w = page.getByRole('region', { name:'Conversation',exact:true })
    async function control(name: string) {
      const d = page.locator('.demo-controls')
      if (await d.getAttribute('open') === null) await d.locator('summary').click()
      await d.getByRole('button', { name,exact:true }).click()
      await d.evaluate(el => (el as HTMLDetailsElement).open = false)
      await page.evaluate(() => window.scrollTo(0,0))
    }
    async function fit() {
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      const over = await page.locator('.workspace-shell, .conversation-content, .working-bar, [data-slot="dialog-content"], [data-slot="sheet-content"]').evaluateAll(els => els.filter(el => el.getClientRects().length && el.scrollWidth > el.clientWidth + 1).map(el => el.className))
      expect(over).toEqual([])
      expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    }
    await page.getByRole('textbox', { name: 'Your message' }).fill('budget 30; expiry 2026-11-12T18:00')
    await page.getByRole('textbox', { name: 'Your message' }).press('Enter')
    await expect(page.getByRole('region', { name: 'Spending review', exact: true })).toBeVisible()
    const authorize = page.getByRole('button', { name:'Authorize mandate' })
    await authorize.scrollIntoViewIfNeeded()
    const box = await authorize.boundingBox()
    const frame = await w.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(frame!.x)
    expect(box!.x + box!.width).toBeLessThanOrEqual(frame!.x + frame!.width)
    await fit()
    await page.screenshot({ path:`${evidence}/responsive-review-${width}.png` })
    await page.getByRole('region', { name: 'Conversation', exact: true }).getByRole('button', { name: 'Edit details', exact: true }).click()
    await fit()
    await page.screenshot({ path:`${evidence}/responsive-editor-${width}.png` })
    await page.getByRole('region', { name: 'Edit draft details', exact: true }).getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Edit draft details', exact: true })).toHaveCount(0)
    await expect(page.getByRole('complementary', { name: 'Working bar', exact: true }).getByRole('button', { name: 'Edit details', exact: true })).toBeFocused()
    await authorize.click()
    await control('Confirm funding')
    await control('S03 · Deliver company records')
    await fit()
    await control('S04 · Excluded recipient request')
    await w.getByRole('heading', { name:'Payment blocked · Recipient not allowed', exact:true }).scrollIntoViewIfNeeded()
    await fit()
    await page.screenshot({ path:`${evidence}/responsive-blocked-${width}.png` })
    if (width < 760) await panel(page).getByRole('button', { name:'Hide panel',exact:true }).click()
    await w.getByRole('button', { name:'Continue without this purchase' }).click()
    await w.getByRole('button', { name:'Stop new spending' }).click()
    await control('Confirm stop')
    await w.getByRole('button', { name:'Check prior payments' }).click()
    await w.getByRole('button', { name:'Request return of 22 TEST' }).click()
    await control('Confirm return')
    if (width < 760) await page.getByRole('button', { name:'Show task panel',exact:true }).click()
    await expect(panel(page).getByTestId('ledger')).toHaveText('Spent8 TESTReserved0 TESTAvailable0 TESTRecovered22 TEST')
    await expect(panel(page).getByText('Background research · Not started · Task stopped', { exact:true })).toBeVisible()
    await fit()
    if (width < 760) {
      const sheet = panel(page)
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await sheet.getByText('Background research · Not started · Task stopped', { exact:true }).scrollIntoViewIfNeeded()
      await fit()
      await page.screenshot({ path:`${evidence}/responsive-workingbar-${width}.png` })
      await sheet.getByRole('button', { name:/^(?:Open company records receipt|Open receipt — company records)$/ }).click()
      await expect(page.getByRole('dialog', { name:'Company records receipt' })).toContainText('DEMO-RECORDS-01')
      await fit()
      await page.screenshot({ path:`${evidence}/responsive-nested-receipt-${width}.png` })
      await page.keyboard.press('Escape')
      await expect(sheet.getByRole('button', { name:/^(?:Open company records receipt|Open receipt — company records)$/ })).toBeFocused()
      await sheet.getByRole('button', { name:'Hide panel',exact:true }).click()
      await expect(page.getByRole('button', { name:'Show task panel',exact:true })).toBeFocused()
    }
  })
}
