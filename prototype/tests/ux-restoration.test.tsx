import { expect, test } from 'vitest'
import { createState, transition as go, defaultDraft, validDraft, ledger } from '../src/demo/model'

test('stop during funding latches against later confirmation, no purchase can start and funding replay is idempotent', () => {
 let s=go(go(createState(),{type:'EXTERNAL'}),{type:'AUTHORIZE'})
 expect(go(s,{type:'REQUEST',id:'early',amount:200,recipient:'records'}).orders).toHaveLength(0)
 s=go(s,{type:'STOP'})
 expect(s.fundingStopped).toBe(true)
 const auth=s.authorized
 s=go(s,{type:'FUNDING_CONFIRMED'})
 expect(s.phase).toBe('stopped')
 expect(s.authorized).toEqual(auth)
 expect(s.funded).toBe(3000)
 expect(go(s,{type:'FUNDING_CONFIRMED'})).toEqual(s)
 expect(go(s,{type:'REQUEST',id:'late',amount:200,recipient:'records'}).orders).toHaveLength(0)
})
test('replayed blocked attempt cannot rewrite its historical ledger or duplicate Activity', () => {
 let s=go(go(go(createState(),{type:'EXTERNAL'}),{type:'AUTHORIZE'}),{type:'FUNDING_CONFIRMED'})
 const attempt={type:'REQUEST',id:'excluded',recipient:'excluded' as const,amount:200}
 s=go(s,attempt)
 const block=structuredClone(s.blocks[0])
 s=go(go(s,{type:'REQUEST',id:'r',recipient:'records',amount:800}),{type:'PAID',id:'r'})
 expect(go(s,attempt)).toEqual(s)
 expect(go(s,attempt).blocks[0]).toEqual(block)
})
test('Activity retains ordered events and unchanged ledger through block, continuation and idempotent replays', () => {
 let s=go(go(go(createState(),{type:'EXTERNAL'}),{type:'AUTHORIZE'}),{type:'FUNDING_CONFIRMED'})
 const before=ledger(s)
 s=go(s,{type:'REQUEST',id:'DEMO-EXCLUDED-03',recipient:'excluded',amount:200})
 expect(ledger(s)).toEqual(before)
 expect(s.activity.at(-1)?.text).toMatch(/Recipient not allowed/)
 const count=s.activity.length
 s=go(s,{type:'CONTINUE',id:'DEMO-EXCLUDED-03'})
 expect(s.blocks).toHaveLength(1)
 expect(s.activity).toHaveLength(count+1)
 expect(go(s,{type:'CONTINUE',id:'DEMO-EXCLUDED-03'})).toEqual(s)
 expect(s.blocks[0].spending).toEqual(before)
})
test('amendment is a separate proposal and explicit reauthorization never mutates live terms or accounting', () => {
 let s=go(go(go(createState(),{type:'EXTERNAL'}),{type:'AUTHORIZE'}),{type:'FUNDING_CONFIRMED'})
 const auth=structuredClone(s.authorized), money=ledger(s)
 s=go(s,{type:'PROPOSE_CHANGE'})
 expect(s.proposal).toEqual(auth)
 s=go(s,{type:'EDIT_PROPOSAL',draft:{...defaultDraft,budget:'40',records:false}})
 expect(s.authorized).toEqual(auth)
 expect(s.proposal?.budget).toBe('40')
 expect(s.proposal).not.toHaveProperty('excluded')
 s=go(s,{type:'REAUTHORIZE_PROPOSAL'})
 expect(s.approvedProposal?.budget).toBe('40')
 expect(s.authorizationHistory).toEqual([auth])
 expect(s.authorized).toEqual(auth)
 expect(ledger(s)).toEqual(money)
 expect(s.note).toMatch(/carryover.*not defined/i)
 expect(go(s,{type:'REAUTHORIZE_PROPOSAL'})).toEqual(s)
 s=go(s,{type:'STOP'})
 expect(s.authorized).toEqual(auth)
 expect(s.phase).toBe('stopRequested')
})

test('missing information is asked for, never supplied as an unconfirmed budget or expiry', () => {
 const s = go(createState(), {type:'SEND', text:'Check Northwind Print before I sign. I need a short brief with the evidence.'})
 expect(s.draft.budget).toBe('')
 expect(s.provenance.output).toBe('Proposed by agent · Based on your request; includes purchase receipts')
 expect(s.draft.expiry).toBe('')
 expect(s.messages.at(-1)?.text).toMatch(/budget.*expiry/i)
 expect(validDraft(s.draft)).toBe(false)
 expect(go({...s,phase:'review'},{type:'AUTHORIZE'}).authorized).toBeNull()
})
test('complete plain-language request with explicit TEST limit and UTC expiry skips missing-field questions', () => {
 const s=go(createState(),{type:'SEND',text:'Check Northwind Print before I sign. I need a short brief with the evidence. Up to 30 TEST, until 2026-11-12T18:00 UTC.'})
 expect(s.phase).toBe('review');expect(s.draft.budget).toBe('30');expect(s.draft.expiry).toBe('2026-11-12T18:00')
 expect(s.draft.output).toMatch(/receipts/)
})
test('complete request goes directly to common review, provenance follows actual request and chat', () => {
 let s=go(createState(),{type:'SEND',text:'job Check Northwind Print before signing; output Short brief with evidence and receipts; budget 30; expiry 2026-11-12T18:00'})
 expect(s.phase).toBe('review')
 expect(s.authorized).toBeNull()
 expect(s.provenance.budget).toBe('From your request')
 s=go(s,{type:'SEND',text:'budget 24'})
 expect(s.provenance.budget).toBe('From chat')
 expect(s.draft.budget).toBe('24')
 expect(s.provenance.records).toBe('Proposed by agent · Needs review')
 const external=go(createState(),{type:'EXTERNAL'})
 expect(external.draft).toEqual(defaultDraft)
 expect(external.draft.output).toMatch(/receipts/)
 expect(go(external,{type:'AUTHORIZE'}).phase).toBe('funding')
 expect(ledger(s)).toEqual({spent:0,reserved:0,available:0,recovered:0})
})
