test('payment blocked detail is lateral, preserves email claim, allowlist and ledger; Continue retains reopen via Activity',async()=>{
 const user=await active();await user.click(screen.getByRole('button',{name:'S03 · Deliver company records'}));await user.click(screen.getByRole('button',{name:'S04 · Excluded recipient request'}))
 const conversation=screen.getByRole('region',{name:'Conversation'})
 expect(conversation).toHaveTextContent('verification@northwind.example')
 expect(conversation).toHaveTextContent('Untrusted content')
 expect(conversation).toHaveTextContent(/amount fits the budget/i)
 await user.click(within(conversation).getByRole('button',{name:'View details'}))
 const panel=screen.getByRole('complementary',{name:'Working bar'})
 expect(panel).toHaveTextContent('What the email claims');expect(panel).toHaveTextContent('What the system established')
 expect(panel).toHaveTextContent('FIXTURE-RECIPIENT-001');expect(panel).toHaveTextContent('FIXTURE-RECIPIENT-002')
 expect(panel).toHaveTextContent('Spent 8 TEST · Reserved 0 TEST · Available 22 TEST · Unchanged')
 await user.click(within(panel).getByRole('button',{name:'Continue without this purchase'}))
 const activity=within(panel).getByRole('region',{name:'Activity'})
 await user.click(within(activity).getByRole('button',{name:'View details'}))
 expect(panel).toHaveTextContent('What the system established')
 expect(screen.getByLabelText('Your message')).toBeEnabled()
})
