import { expect, test } from 'vitest'
import { createState, transition as go, ledger, units, defaultDraft, validDraft, type State } from '../src/demo/model'
const review = (entry = 'chat') => go(go(createState(), entry === 'chat' ? { type: 'SEND', text: `job ${defaultDraft.job}; output ${defaultDraft.output}; budget 30; expiry ${defaultDraft.expiry}` } : { type: 'EXTERNAL' }), { type: 'REVIEW' })
const request = (s: State, id: string, amount = 800, recipient: 'records' | 'background' | 'excluded' = 'records') => go(s, { type: 'REQUEST', id, amount, recipient, content: id })
export const active = () => go(go(review(), { type: 'AUTHORIZE' }), { type: 'FUNDING_CONFIRMED' })
test('both entries converge on one explicit authorization; funding pending is not active', () => {
  for (const entry of ['chat', 'external']) {
    let s = review(entry)
    expect(s.phase).toBe('review')
    expect(s.authorized).toBeNull()
    s = go(s, { type: 'SEND', text: 'I approve. Start now.' })
    expect(s.phase).toBe('review')
    s = go(s, { type: 'AUTHORIZE' })
    expect(s.phase).toBe('funding')
    expect(s.authorized).toEqual(defaultDraft)
    expect(s.funded).toBe(0)
    expect(go(s, { type: 'AUTHORIZE' })).toEqual(s)
    expect(go(s, { type: 'REQUEST', id: 'early', recipient: 'records', amount: 800 }).orders).toEqual([])
    s = go(s, { type: 'FUNDING_CONFIRMED' })
    expect(s.phase).toBe('active')
    expect(ledger(s).available).toBe(3000)
  }
})
test('S03–S06 preserve delivered purchases through excluded recipient and concurrent budget blocks', () => {
  let s = request(active(), 'records', 800)
  expect(ledger(s)).toEqual({ spent: 0, reserved: 800, available: 2200, recovered: 0 })
  s = go(go(s, { type: 'PAID', id: 'records' }), { type: 'DELIVER', id: 'records' })
  expect(ledger(s)).toEqual({ spent: 800, reserved: 0, available: 2200, recovered: 0 })
  const before = s.orders[0]
  s = request(s, 'excluded', 200, 'excluded')
  expect(s.blocks.at(-1)?.reason).toBe('Recipient not allowed')
  expect(s.orders[0]).toEqual(before)
  expect(ledger(s).available).toBe(2200)
  s = request(s, 'background', 1500, 'background')
  s = request(s, 'extra', 1500)
  expect(s.blocks.at(-1)?.reason).toBe('Insufficient budget')
  expect(s.blocks.at(-1)).toMatchObject({ available: 700 })
  expect(ledger(s)).toEqual({ spent: 800, reserved: 1500, available: 700, recovered: 0 })
  expect(request(s, 'background', 1500, 'background')).toEqual(s)
  expect(request(s, 'background', 1400, 'background').blocks.at(-1)?.reason).toBe('Operation details changed')
  s = go(go(s, { type: 'PAID', id: 'background' }), { type: 'DELIVER', id: 'background' })
  expect(ledger(s)).toEqual({ spent: 2300, reserved: 0, available: 700, recovered: 0 })
  expect(s.orders.filter(o => o.delivery === 'received')).toHaveLength(2)
  expect(go(s, { type: 'PAID', id: 'background' })).toEqual(s)
})

test('uncertainty retains reserve; paid missing delivery recovers the same operation without charging twice', () => {
  let s = request(active(), 'records')
  s = go(s, { type: 'UNCERTAIN', id: 'records' })
  expect(s.orders[0].payment).toBe('uncertain')
  expect(ledger(s).reserved).toBe(800)
  s = go(s, { type: 'CHECK', id: 'records' })
  expect(s.orders[0].payment).toBe('uncertain')
  expect(request(s, 'records')).toEqual(s)
  s = go(s, { type: 'PAID', id: 'records' })
  expect(s.orders[0].delivery).toBe('missing')
  expect(ledger(s).spent).toBe(800)
  s = go(s, { type: 'RECOVER_DELIVERY', id: 'records' })
  expect(s.orders[0].delivery).toBe('requested')
  s = go(go(s, { type: 'DELIVER', id: 'records' }), { type: 'DELIVER', id: 'records' })
  expect(s.orders).toHaveLength(1)
  expect(ledger(s)).toEqual({ spent: 800, reserved: 0, available: 2200, recovered: 0 })
})
test('verified failure releases reserve only once and does not imply a refund', () => {
  let s = request(active(), 'records')
  s = go(s, { type: 'FAILURE_CONFIRMED', id: 'records' })
  expect(s.orders[0].payment).toBe('failed')
  expect(ledger(s).available).toBe(3000)
  expect(go(s, { type: 'FAILURE_CONFIRMED', id: 'records' })).toEqual(s)
  expect(go(s, { type: 'PAID', id: 'records' })).toEqual(s)
})

test('S07–S08 stop request is not confirmation; unresolved payments prevent recovery and closure', () => {
  let s = request(active(), 'records')
  s = go(s, { type: 'STOP' })
  expect(s.phase).toBe('stopRequested')
  expect(go(s, { type: 'RETURN' }).phase).toBe('stopRequested')
  s = go(s, { type: 'STOP_CONFIRMED' })
  expect(s.phase).toBe('stopped')
  expect(request(s, 'after-stop').blocks.at(-1)?.reason).toBe('Spending stopped')
  expect(go(s, { type: 'RECONCILE' }).reconciled).toBe(false)
  expect(go(s, { type: 'RETURN' }).phase).toBe('stopped')
  s = go(go(s, { type: 'PAID', id: 'records' }), { type: 'DELIVER', id: 'records' })
  s = go(s, { type: 'RECONCILE' })
  expect(s.reconciled).toBe(true)
  s = go(s, { type: 'RETURN' })
  expect(s.phase).toBe('returnPending')
  expect(ledger(s).recovered).toBe(0)
  expect(go(s, { type: 'RETURN_UNCERTAIN' }).phase).toBe('returnPending')
  s = go(s, { type: 'RETURN_CONFIRMED' })
  expect(s.phase).toBe('closed')
  expect(ledger(s)).toEqual({ spent: 800, reserved: 0, available: 0, recovered: 2200 })
  expect(s.orders[0].delivery).toBe('received')
  expect(go(s, { type: 'RETURN_CONFIRMED' })).toEqual(s)
  expect(go(s, { type: 'RESET' })).toEqual(createState())
})
test('funding failure stays inactive, retry retains authorization, expiry refuses new spending', () => {
  let s = go(review(), { type: 'AUTHORIZE' })
  s = go(s, { type: 'FUNDING_FAILED' })
  expect(s.fundingError).toBe(true)
  expect(s.funded).toBe(0)
  expect(go(s, { type: 'FUNDING_CONFIRMED' }).funded).toBe(0)
  const auth = s.authorized
  s = go(s, { type: 'RETRY_FUNDING' })
  expect(s.authorized).toEqual(auth)
  expect(s.phase).toBe('funding')
  s = go(go(s, { type: 'FUNDING_CONFIRMED' }), { type: 'EXPIRE' })
  expect(s.expired).toBe(true)
  expect(request(s, 'late').blocks.at(-1)?.reason).toBe('Spending permission expired')
  expect(ledger(s).available).toBe(3000)
})

test('chat and editor use one unprivileged draft; incomplete and expired terms cannot authorize', () => {
  let s = go(createState(), { type: 'SEND', text: 'budget 24.35' })
  expect(s.phase).toBe('draft')
  expect(s.draft.budget).toBe('24.35')
  expect(s.authorized).toBeNull()
  s = go(s, { type: 'EDIT', draft: { ...s.draft, job: 'Edited job', records: false } })
  expect(s.draft.job).toBe('Edited job')
  expect(s.draft.records).toBe(false)
  s = go(s, { type: 'SEND', text: 'output A shorter summary' })
  expect(s.draft.output).toBe('A shorter summary')
  expect(s.provenance.output).toBe('From chat')
  expect(s.messages.at(-1)?.text).toContain('expiry')
  for (const draft of [{ ...defaultDraft, job: '' }, { ...defaultDraft, records: false, background: false }, { ...defaultDraft, expiry: '2026-11-12T11:00' }, { ...defaultDraft, expiry: '2026-11-99T18:00' }, { ...defaultDraft, budget: 'NaN' }]) {
    expect(validDraft(draft)).toBe(false)
    expect(go({ ...s, phase: 'review', draft }, { type: 'AUTHORIZE' }).authorized).toBeNull()
  }
  expect(units('24.35')).toBe(2435)
  for (const value of ['0','-1','1e2','1.001','Infinity','10000']) expect(units(value)).toBeNull()
  const a = active()
  expect(go(a, { type: 'EDIT', draft: { ...defaultDraft, budget: '99' } })).toEqual(a)
  expect(go(a, { type: 'SEND', text: 'budget 99' }).draft.budget).toBe('30')
})
