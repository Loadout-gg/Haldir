export const ORIGIN = 'https://api.demo.agentsonintents.com';
export const ATTEMPT = 'owner-qualification-02';
const ROOT = new URL('../../', import.meta.url);
export const DIRECTORY = new URL('.hermes/proposals/attempts/owner-qualification-02/', ROOT);
export const LEGAL = new URL('.hermes/proposals/owner-signing-authorization.md', ROOT);
export const EXPECTED_REQUEST = {
  type: 'agent_create', name: 'U01 - owner qualification',
  owner: { type: 'near', account_id: 'derekblueeyes.near',
    public_key: 'ed25519:9NhWWwbwT2b3o4AdxQfTi9WQ8MYbPQtuzeR6V4KKC4cR' },
  policy: { frozen: true, actions: [], confidential: false, owner_approval: false,
    assets: [], limits: {}, max_actions_per_hour: 1,
    destinations: { mode: 'only', list: [] },
    budget: { daily_usd: '0', weekly_usd: '0', monthly_usd: '0' }, timelock_ms: 0 },
};
const APPROVAL_KEYS = ['schema','origin','attempt','type','correlation_id',
  'request_sha256','generated_sha256','signature_sha256','payload_sha256',
  'legal_record_sha256','owner','policy','owner_authorized_submit','legal_gate_cleared'];
const STATES = new Set(['PENDING_SIGNATURE','QUEUED','PENDING_APPROVAL','PENDING_DEPOSIT',
  'PROCESSING','SUCCESS','REFUNDED','FAILED','UNCERTAIN','NEEDS_REVIEW']);
const path = name => new URL(name, DIRECTORY);
export const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
function exactKeys(value, keys) {
  assert.ok(value && typeof value === 'object' && !Array.isArray(value));
  assert.deepEqual(Object.keys(value).sort(), [...keys].sort());
}
function digest(value) { assert.match(value, /^[a-f0-9]{64}$/); }
function safeId(value) { assert.match(value, /^intent_[A-Za-z0-9_-]{1,200}$/); }
function fresh(g, now) {
  assert.ok(Number.isFinite(Date.parse(g.expires_at)) && now() < Date.parse(g.expires_at));
}

// Bind independent local approval, fixed expected request, generated bytes and saved signature.
// No credential access or transport in this function. Reconcile omits reusable signature reads.
export function bindRecords(records, { submit = false, now = Date.now,
  expected = EXPECTED_REQUEST } = {}) {
  const request = JSON.parse(records.request);
  const g = JSON.parse(records.generated);
  const a = JSON.parse(records.approval);
  assert.deepEqual(request, expected);
  exactKeys(a, APPROVAL_KEYS);
  assert.equal(a.schema, 'u01-owner-submit-approval-v1');
  assert.equal(a.origin, ORIGIN); assert.equal(a.attempt, ATTEMPT);
  assert.equal(a.type, 'agent_create');
  for (const field of ['request_sha256','generated_sha256','signature_sha256',
    'payload_sha256','legal_record_sha256']) digest(a[field]);
  assert.equal(a.request_sha256, sha256(records.request));
  assert.equal(a.generated_sha256, sha256(records.generated));
  assert.deepEqual(a.owner, expected.owner); assert.deepEqual(a.policy, expected.policy);
  assert.equal(g.type, 'agent_create'); assert.equal(g.status, 'PENDING_SIGNATURE');
  safeId(g.correlation_id); assert.equal(a.correlation_id, g.correlation_id);
  assert.deepEqual(g.signer, expected.owner);
  assert.deepEqual(g.preview?.policy, expected.policy);
  assert.equal(g.intent?.standard, 'nep366');
  assert.equal(g.intent.payload?.receiverId, 'outlayer.near');
  assert.equal(a.payload_sha256, sha256(JSON.stringify(g.intent)));
  assert.equal(g.intent.payload.actions?.length, 2);
  const methods = ['store_wallet_policy','freeze_wallet'];
  const deposits = ['12630000000000000000000','0'];
  for (const [i, action] of g.intent.payload.actions.entries()) {
    assert.equal(action.type, 'FunctionCall');
    assert.equal(action.params?.methodName, methods[i]);
    assert.equal(action.params?.deposit, deposits[i]);
    assert.match(action.params.gas, /^[1-9][0-9]*$/);
    assert.ok(action.params.args && typeof action.params.args === 'object' &&
      !Array.isArray(action.params.args));
  }
  // g.agent_id is allowed to be null before creation; it is never invented by this operator.
  assert.ok(g.agent_id === null || (typeof g.agent_id === 'string' && /^[a-f0-9]{64}$/.test(g.agent_id)));
  if (!submit) return { g, a };
  assert.equal(a.owner_authorized_submit, true);
  assert.equal(a.legal_gate_cleared, true);
  assert.equal(a.legal_record_sha256, sha256(records.legal));
  assert.equal(a.signature_sha256, sha256(records.signature));
  const signed = JSON.parse(records.signature);
  exactKeys(signed, ['correlation_id','type','signed_data']);
  assert.equal(signed.correlation_id, g.correlation_id);
  assert.equal(signed.type, 'agent_create');
  validateSignature(signed.signed_data, g, expected.owner);
  fresh(g, now);
  return { g, a, request: { type: 'agent_create', correlation_id: g.correlation_id,
    signed_data: signed.signed_data } };
}

// Drop all unrecognized fields and raw failures; do not print provider-controlled text.
export function statusReport(response, g, source) {
  assert.ok(response && typeof response === 'object');
  assert.equal(response.correlation_id, g.correlation_id);
  assert.equal(response.type, 'agent_create');
  assert.ok(STATES.has(response.status));
  assert.ok(response.agent_id === null ||
    (typeof response.agent_id === 'string' && /^[a-f0-9]{64}$/.test(response.agent_id)));
  if (g.agent_id !== null) assert.equal(response.agent_id, g.agent_id);
  if (response.status === 'SUCCESS') {
    assert.match(response.agent_id, /^[a-f0-9]{64}$/);
    assert.equal(response.details?.agent_id, response.agent_id);
  }
  return { state: 'STATUS_OBSERVED', source, correlation_id: g.correlation_id,
    type: 'agent_create', status: response.status, agent_id: response.agent_id,
    observed_success: source === 'status_read' && response.status === 'SUCCESS',
    lifecycle_complete: false };
}

// io.fetch is mandatory: tests provide a synthetic transport, CLI supplies global fetch.
// Every submit, including a rejected/uncertain one, consumes this local journal forever.
export async function runOwner(mode, io, expected = EXPECTED_REQUEST) {
  if (!['submit','reconcile'].includes(mode)) return { state: 'REFUSED', reason: 'usage' };
  let g, journalCreated = false, writeStarted = false;
  try {
    if (mode === 'submit') assert.equal(await io.exists(path('owner-submit-attempt.json')), false);
    const records = {
      request: await io.read(path('owner-qualification.json')),
      generated: await io.read(path('owner-intent-generated.json')),
      approval: await io.read(path('owner-submit-approval.json')),
    };
    if (mode === 'submit') {
      records.signature = await io.read(path('owner-signature.json'));
      records.legal = await io.read(LEGAL);
    }
    const bound = bindRecords(records, { submit: mode === 'submit', now: io.now, expected });
    g = bound.g;
    assert.equal(typeof io.fetch, 'function');
    // Only the separately invoked CLI implements this as an environment read.
    const apiKey = await io.loadKey();
    assert.ok(typeof apiKey === 'string' && apiKey.length > 0);
    const api = createAgentApi({ apiKey, baseUrl: ORIGIN, fetch: io.fetch,
      timeoutMs: 25000, maxResponseBytes: 262144 });
    if (mode === 'reconcile') {
      // No journal/outcome/stat writes, no signature/legal read, no freshness or approval grant.
      return statusReport(await api.getStatus(g.correlation_id, { waitMs: 0 }), g, 'status_read');
    }
    fresh(g, io.now);
    const journal = { schema: 'u01-owner-submit-attempt-v1', origin: ORIGIN, attempt: ATTEMPT,
      type: 'agent_create', correlation_id: g.correlation_id,
      request_sha256: bound.a.request_sha256, generated_sha256: bound.a.generated_sha256,
      signature_sha256: bound.a.signature_sha256, approval_sha256: sha256(records.approval),
      state: 'PREPARED_OUTCOME_UNKNOWN', started_at: new Date(io.now()).toISOString() };
    // exclusive must finish write + fsync + close before resolving. A partial write also blocks retries.
    await io.exclusive(path('owner-submit-attempt.json'), JSON.stringify(journal),
      { flag: 'wx', mode: 0o600 });
    journalCreated = true;
    fresh(g, io.now); // Expiry during persistence consumes the journal but must not submit.
    writeStarted = true;
    const report = statusReport(await api.submitIntent(bound.request), g, 'submit_response');
    await io.exclusive(path('owner-submit-outcome.json'), JSON.stringify(report),
      { flag: 'wx', mode: 0o600 });
    return { ...report, next: 'READ_ONLY_RECONCILE' };
  } catch {
    // Do not inspect/log error.message, stack, cause, headers or API error objects.
    if (writeStarted) {
      const report = { state: 'OUTCOME_UNCERTAIN', correlation_id: g.correlation_id,
        lifecycle_complete: false, next: 'READ_ONLY_RECONCILE' };
      try { await io.exclusive(path('owner-submit-outcome.json'), JSON.stringify(report),
        { flag: 'wx', mode: 0o600 }); } catch { /* Preserve all existing/partial evidence. */ }
      return report;
    }
    return { state: 'REFUSED', reason: journalCreated ? 'journal_consumed_no_submit' :
      'preflight_or_read_failed', lifecycle_complete: false, next: 'PRESERVE_RECORDS' };
  }
}

// Production IO is constructed only by main; importing this module reads no private files/key.
export function localIO() {
  return {
    now: Date.now,
    fetch: globalThis.fetch,
    loadKey: () => process.env.NEAR_INTENTS_AGENT_API_KEY,
    async exists(file) {
      try { await lstat(file); return true; }
      catch (error) { if (error.code === 'ENOENT') return false; throw error; }
    },
    async read(file) {
      // O_NOFOLLOW on open + fstat avoids following a substituted final symlink.
      const { constants } = await import('node:fs');
      const handle = await open(file, constants.O_RDONLY | constants.O_NOFOLLOW);
      try {
        const stat = await handle.stat();
        assert.ok(stat.isFile() && stat.size <= 1048576 && (stat.mode & 0o077) === 0);
        return await handle.readFile('utf8');
      } finally { await handle.close(); }
    },
    async exclusive(file, text, options) {
      assert.deepEqual(options, { flag: 'wx', mode: 0o600 });
      const handle = await open(file, options.flag, options.mode);
      try { await handle.writeFile(text, 'utf8'); await handle.sync(); }
      finally { await handle.close(); }
    },
  };
}
export async function main(args = process.argv.slice(2), io = localIO(),
  emit = text => process.stdout.write(text + '\n')) {
  // Exact arity; do not interpret key/path/origin/approval overrides.
  const result = args.length === 1 ? await runOwner(args[0], io) :
    { state: 'REFUSED', reason: 'usage' };
  emit(JSON.stringify(result));
  return ['REFUSED','OUTCOME_UNCERTAIN'].includes(result.state) ? 1 : 0;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().then(code => { process.exitCode = code; }, () => {
    process.stdout.write('{"state":"REFUSED","reason":"operator_failed"}\n');
    process.exitCode = 1;
  });
}
