 await user.click(screen.getByRole('button',{name:'Ask a question'}));expect(screen.getByLabelText('Your message')).toHaveFocus()
 await user.click(screen.getByRole('button',{name:'Authorize mandate'}))
 expect(screen.getByRole('region',{name:'Activation status'})).toHaveTextContent('AuthorizationConfirmed')
