const now = Date.parse('2030-01-01T00:00:00Z');
const nonce = Uint8Array.from({ length: 32 }, (_, i) => i);
function fixture() {
  const pair = KeyPair.fromRandom('ed25519'); // Ephemeral synthetic fixture only.
  const publicKey = pair.getPublicKey().toString();
  const generated = {
    correlation_id: `intent_${'A'.repeat(43)}`, type: 'grant_issue', agent_id: 'a'.repeat(64),
    status: 'PENDING_SIGNATURE', expires_at: '2030-01-01T00:01:00Z',
    signer: { type: 'near', account_id: 'synthetic.near', public_key: publicKey },
    intent: { standard: 'nep413', payload: {
      message: '{ "z": "synthetic consent — not a grant token", "a": 1 }',
      recipient: 'synthetic.invalid', nonce: Buffer.from(nonce).toString('base64'),
    } }, preview: { summary: 'Synthetic offline qualification only' },
  };
  return { pair, publicKey, generated };
}

test('prepares exact Meteor message request without changing original intent', () => {
  const { generated, publicKey } = fixture();
  const before = structuredClone(generated);
  const prepared = prepareNep413(generated, publicKey, { clock: () => now });
  assert.deepEqual(prepared.request, { id: 'near::sign_message', input: {
    target: { blockchain: 'near', network: 'mainnet', accountId: 'synthetic.near' },
    messageParams: { message: generated.intent.payload.message, recipient: 'synthetic.invalid', nonce },
  } });
  assert.equal(Object.hasOwn(prepared.request.input.messageParams, 'callbackUrl'), false);
  assert.deepEqual(generated, before);
});

test('passes callbackUrl only when explicitly present in generated payload', () => {
  const { generated, publicKey } = fixture();
  generated.intent.payload.callbackUrl = 'https://synthetic.invalid/callback';
  const before = structuredClone(generated.intent);
  const prepared = prepareNep413(generated, publicKey, { clock: () => now });
  assert.equal(prepared.request.input.messageParams.callbackUrl, generated.intent.payload.callbackUrl);
  assert.deepEqual(generated.intent, before);
});

for (const [label, mutate] of [
  ['31-byte nonce', g => { g.intent.payload.nonce = Buffer.alloc(31).toString('base64'); }],
  ['33-byte nonce', g => { g.intent.payload.nonce = Buffer.alloc(33).toString('base64'); }],
  ['noncanonical nonce padding bits', g => { g.intent.payload.nonce = g.intent.payload.nonce.slice(0, -2) + '9='; }],
  ['whitespace nonce', g => { g.intent.payload.nonce += '\n'; }],
  ['base64url nonce', g => { g.intent.payload.nonce = '_'.repeat(43) + '='; }],
  ['nonstring nonce', g => { g.intent.payload.nonce = nonce; }],
  ['wrong signing standard', g => { g.intent.standard = 'nep366'; }],
  ['missing message', g => { delete g.intent.payload.message; }],
  ['nonstring message', g => { g.intent.payload.message = {}; }],
  ['empty recipient', g => { g.intent.payload.recipient = ''; }],
  ['extra payload field', g => { g.intent.payload.state = 'not generated by API'; }],
  ['invalid callback', g => { g.intent.payload.callbackUrl = null; }],
  ['expired intent', g => { g.expires_at = '2030-01-01T00:00:00Z'; }],
  ['invalid expiry', g => { g.expires_at = 'invalid'; }],
  ['nonpending intent', g => { g.status = 'APPLIED'; }],
  ['nonNEAR signer', g => { g.signer.type = 'evm'; }],
  ['missing account', g => { delete g.signer.account_id; }],
  ['wrong owner key', g => { g.signer.public_key = KeyPair.fromRandom('ed25519').getPublicKey().toString(); }],
]) test(`refuses ${label} before preparing a signing request`, () => {
  const { generated, publicKey } = fixture();
  mutate(generated);
  assert.throws(() => prepareNep413(generated, publicKey, { clock: () => now }), /nonce|payload|expired|expiry|pending|signer|account|key|standard/i);
});

test('refuses malformed expected key and nonfinite clock', () => {
  const { generated, publicKey } = fixture();
  for (const key of [undefined, publicKey.slice(8), 'ed25519:not-a-key', `ED25519:${publicKey.slice(8)}`]) {
    assert.throws(() => prepareNep413(generated, key, { clock: () => now }), /key/i);
  }
  assert.throws(() => prepareNep413(generated, publicKey, { clock: () => NaN }), /clock/i);
});

async function signFixture(pair, params) {
  return new KeyPairSigner(pair).signNep413Message('synthetic.near', params);
}

for (const callbackUrl of [undefined, 'https://synthetic.invalid/callback', '']) {
  test(`encodes raw SDK signature bytes as base64 and preserves payload (callback ${JSON.stringify(callbackUrl)})`, async () => {
    const { generated, publicKey, pair } = fixture();
    if (callbackUrl !== undefined) generated.intent.payload.callbackUrl = callbackUrl;
    const before = structuredClone(generated.intent);
    const prepared = prepareNep413(generated, publicKey, { clock: () => now });
    const output = await signFixture(pair, prepared.request.input.messageParams);
    const signatureBefore = output.signature.slice();
    assert.deepEqual(await prepared.signedData(output), {
      ...before, public_key: publicKey, signature: Buffer.from(output.signature).toString('base64'),
    });
    assert.deepEqual(generated.intent, before);
    assert.deepEqual(output.signature, signatureBefore);
  });
}

for (const [label, mutate] of [
  ['different returned key', (o) => { o.publicKey = KeyPair.fromRandom('ed25519').getPublicKey(); }],
  ['different returned account', (o) => { o.accountId = 'other.near'; }],
  ['null returned account', (o) => { o.accountId = null; }],
  ['spoofed key toString', (o, key) => { o.publicKey = { toString: () => key }; }],
  ['ambiguous key variant', (o) => { o.publicKey.secp256k1Key = { data: new Uint8Array(64) }; }],
  ['wrong signature bytes', (o) => { o.signature[0] ^= 1; }],
  ['short signature', (o) => { o.signature = o.signature.slice(1); }],
  ['coercible signature array', (o) => { o.signature = Array.from(o.signature, String); }],
]) test(`refuses ${label}`, async () => {
  const { generated, publicKey, pair } = fixture();
  const prepared = prepareNep413(generated, publicKey, { clock: () => now });
  const output = await signFixture(pair, prepared.request.input.messageParams);
  mutate(output, publicKey);
  await assert.rejects(prepared.signedData(output), /key|account|signature/i);
});

for (const [label, change] of [
  ['message', p => { p.message = JSON.stringify(JSON.parse(p.message)); }],
  ['recipient', p => { p.recipient = 'other.invalid'; }],
  ['32-byte nonce', p => { p.nonce[0] ^= 1; }],
  ['added callback', p => { p.callbackUrl = 'https://other.invalid/'; }],
]) test(`refuses valid owner signature over substituted ${label}`, async () => {
  const { generated, publicKey, pair } = fixture();
  const prepared = prepareNep413(generated, publicKey, { clock: () => now });
  const altered = structuredClone(prepared.request.input.messageParams);
  change(altered);
  const output = await signFixture(pair, altered);
  await assert.rejects(prepared.signedData(output), /signature.*payload|payload.*signature/i);
});

test('expiry during approval refuses the response', async () => {
  const { generated, publicKey, pair } = fixture();
  let time = now;
  const prepared = prepareNep413(generated, publicKey, { clock: () => time });
  const output = await signFixture(pair, prepared.request.input.messageParams);
  time += 60_000;
  await assert.rejects(prepared.signedData(output), /expired/i);
});

for (const [label, mutate] of [
  ['original payload', (g) => { g.intent.payload.message = 'substitution'; }],
  ['original expiry', (g) => { g.expires_at = '2030-01-01T01:00:00Z'; }],
  ['request nonce', (_g, p) => { p.request.input.messageParams.nonce[0] ^= 1; }],
  ['request account', (_g, p) => { p.request.input.target.accountId = 'other.near'; }],
]) test(`refuses mutation of ${label} after preparation`, async () => {
  const { generated, publicKey, pair } = fixture();
  const prepared = prepareNep413(generated, publicKey, { clock: () => now });
  const output = await signFixture(pair, prepared.request.input.messageParams);
  mutate(generated, prepared);
  await assert.rejects(prepared.signedData(output), /changed|mismatch/i);
});

test('refuses a contradictory key type even when Ed25519 variant bytes match', async () => {
  const { generated, publicKey, pair } = fixture();
  const prepared = prepareNep413(generated, publicKey, { clock: () => now });
  const output = await signFixture(pair, prepared.request.input.messageParams);
  output.publicKey = { keyType: 1, enum: 'ed25519Key', ed25519Key: { data: pair.getPublicKey().data } };
  await assert.rejects(prepared.signedData(output), /key/i);
});

// Independent serialization + node:crypto verifier, not the adapter's Borsh/verify path.
function independentDigest(params) {
  const string = text => {
    const bytes = Buffer.from(text, 'utf8'), length = Buffer.alloc(4);
    length.writeUInt32LE(bytes.length);
    return Buffer.concat([length, bytes]);
  };
  const tag = Buffer.alloc(4); tag.writeUInt32LE(2147484061);
  const callback = Object.hasOwn(params, 'callbackUrl')
    ? Buffer.concat([Buffer.from([1]), string(params.callbackUrl)]) : Buffer.from([0]);
  return createHash('sha256').update(Buffer.concat([
    tag, string(params.message), Buffer.from(params.nonce), string(params.recipient), callback,
  ])).digest();
}

// Real installed SDK action creation -> V1 client -> postmessenger -> response
// deserializer. Only the transport is synthetic; no prompts, RPC, persisted keys.
test('installed Meteor 3.24.1 deserializes PublicKey + Buffer and adapter retains exact wire shape', { timeout: 5000 }, async t => {
  const pkg = JSON.parse(await readFile(new URL('../../node_modules/@meteorwallet/sdk/package.json', import.meta.url)));
  assert.equal(pkg.version, '3.24.1');
  const { generated, publicKey, pair } = fixture();
  const prepared = prepareNep413(generated, publicKey, { clock: () => now });
  const signed = await signFixture(pair, prepared.request.input.messageParams);
  const wire = { accountId: 'synthetic.near', publicKey, signature: Buffer.from(signed.signature).toString('base64') };
  let requests = 0, fetches = 0, popups = 0, keyAccesses = 0;
  t.mock.method(console, 'log', () => {}); // Upstream has raw console logs.
  t.mock.method(console, 'debug', () => {});
  t.mock.method(globalThis, 'fetch', () => { fetches++; throw new Error('Offline fixture forbids network'); });
  const previousWindow = Object.getOwnPropertyDescriptor(globalThis, 'window');
  t.after(() => { if (previousWindow) Object.defineProperty(globalThis, 'window', previousWindow); else delete globalThis.window; });
  Object.defineProperty(globalThis, 'window', { configurable: true, value: {
    get localStorage() { assert.fail('Persistent storage forbidden'); },
    open() { popups++; assert.fail('Wallet popup forbidden'); },
    meteorCom: {},
    meteorComV2: {
      async sendMessageDataAndRespond(message) {
        if (message.status === 'closed_success') return; // SDK acknowledgment.
        requests++;
        assert.equal(message.actionType, 'sign_message');
        assert.equal(message.inputs.accountId, 'synthetic.near');
        assert.equal(message.inputs.message, generated.intent.payload.message);
        assert.equal(message.inputs.recipient, generated.intent.payload.recipient);
        assert.deepEqual(message.inputs.nonce, nonce);
        assert.equal(message.inputs.callbackUrl, undefined);
        return { uid: message.uid, status: 'closed_success', payload: { ...wire } };
      },
    },
  } });
  const values = new Map();
  const storage = {
    async getItem(k) { return values.get(k) ?? null; },
    async setItem(k, v) { values.set(k, v); }, async removeItem(k) { values.delete(k); },
    async getKeys() { return [...values.keys()]; },
  };
  const noKeys = new Proxy({}, { get() { keyAccesses++; throw new Error('Key access forbidden'); } });
  const wallet = new MeteorConnect({ isDev: false });
  const previousLevel = wallet.getLoggingLevel();
  wallet.setLoggingLevel('none');
  t.after(() => wallet.setLoggingLevel(previousLevel));
  await wallet.initialize({ storage, mobileBridge: { enabled: false }, nearKeyStoreProvider: { getKeyStore: () => noKeys } });
  await wallet.addSignedInAccount({
    identifier: prepared.request.input.target, connection: { executionTarget: 'v1_ext' }, publicKeys: [],
  });
  const action = await wallet.createAction(prepared.request);
  const output = await action.execute('v1_ext');
  assert.equal(output.publicKey instanceof PublicKey, false, 'SDK uses its distinct @near-js/crypto class');
  assert.equal(output.publicKey.toString(), publicKey);
  assert.equal(Buffer.isBuffer(output.signature), true);
  const result = await prepared.signedData(output);
  assert.deepEqual(result, { ...generated.intent, public_key: publicKey, signature: wire.signature });
  assert.deepEqual(Buffer.from(result.signature, 'base64'), Buffer.from(signed.signature));
  const verifier = createPublicKey({ format: 'der', type: 'spki', key: Buffer.concat([
    Buffer.from('302a300506032b6570032100', 'hex'), Buffer.from(pair.getPublicKey().data),
  ]) });
  assert.equal(verify(null, independentDigest(prepared.request.input.messageParams), verifier, Buffer.from(result.signature, 'base64')), true);
  assert.equal(requests, 1);
  assert.deepEqual({ fetches, popups, keyAccesses }, { fetches: 0, popups: 0, keyAccesses: 0 });
});
